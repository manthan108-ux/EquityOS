"""One resumable, batched run over the listed-company universe.

For each company in the next batch the steps below run in order; every step is isolated (an error in
one never stops the others or the batch), idempotent and skips work that is not due:

 1 website     discover, verify and register the official website (once per back-off window)
 2 upstox      refresh Upstox fundamentals if the company is due
 3 documents   fetch newly published public documents from the registered website (7-day cool-down)
 4 enrich      verified history / leadership quotes from the company's own pages (30-day cool-down)
 5 evidence    synchronise and validate the evidence store for the company

Progress lives in the tables each step already keeps (website registry, Upstox refresh state, fetch
runs, enrichment rows), so a stopped run continues where it left off and a repeated run does no
repeated downloads. Reports are generated by the research workflow when a user asks for one, from
whatever this run (and any user upload) has made available.
"""

import logging
from dataclasses import dataclass, field
from datetime import UTC, datetime

from sqlalchemy import case, func, or_, select
from sqlalchemy.orm import Session

from app.models import (
    Company,
    CompanyEnrichment,
    CompanyWebsiteRegistry,
    EvidenceFetchRun,
    ProviderRefreshState,
    Security,
)

log = logging.getLogger("equityos.universe")
STEPS = ("website", "upstox", "documents", "enrich", "evidence")


@dataclass
class CompanyRun:
    name: str
    steps: dict[str, str] = field(default_factory=dict)


@dataclass
class UniverseRun:
    companies: list[CompanyRun] = field(default_factory=list)
    stopped: str | None = None


def pick_batch(session: Session, limit: int, now: datetime | None = None) -> list[Company]:
    """The companies that most need work, so every run advances the universe.

    Tier 0: never tried (no website-registry row).  Tier 1: a failed/ambiguous website whose retry
    window has opened.  Tier 2: no Upstox refresh recorded yet.  Tier 3: everything else (cheap
    no-ops thanks to the per-step cool-downs).  NSE-listed first inside a tier, then name order.
    A company whose website is in its retry back-off and whose Upstox data exists is not picked
    ahead of work that is actually due - the old ordering kept returning the same failures.
    """
    now = now or datetime.now(UTC)
    reg = CompanyWebsiteRegistry
    never_tried = ~select(reg.company_id).where(reg.company_id == Company.id).exists()
    retry_due = (
        select(reg.company_id)
        .where(
            reg.company_id == Company.id,
            reg.status.notin_(("VERIFIED", "MANUAL")),
            or_(reg.next_retry_at.is_(None), reg.next_retry_at <= now),
        )
        .exists()
    )
    no_upstox = (
        ~select(ProviderRefreshState.company_id)
        .where(
            ProviderRefreshState.company_id == Company.id,
            ProviderRefreshState.provider_code == "UPSTOX_FUNDAMENTALS",
        )
        .exists()
    )
    tier = case((never_tried, 0), (retry_due, 1), (no_upstox, 2), else_=3)
    q = (
        select(Company)
        .join(Security, Security.company_id == Company.id)
        .where(Security.isin.is_not(None))
        .group_by(Company.id)
        .order_by(
            tier,
            func.bool_or(Security.security_code.is_(None)).desc(),
            Company.common_name,
        )
        .limit(limit)
    )
    return list(session.scalars(q))


def run_company(session: Session, company: Company, *, steps, client, llm, upstox) -> CompanyRun:
    out = CompanyRun(company.common_name)

    def step(name: str, fn) -> None:
        if name not in steps:
            return
        try:
            out.steps[name] = fn() or "done"
        except Exception as exc:  # noqa: BLE001 - failure isolation: record and carry on
            session.rollback()
            log.exception("%s step failed for %s", name, company.common_name)
            out.steps[name] = f"error: {type(exc).__name__}"

    def website():
        from app.acquisition import website_discovery as wd

        res = wd.discover(session, company, client, llm, use_llm=llm is not None)
        return f"{res.status}{(' - ' + res.note) if res.note else ''}"

    def upstox_step():
        if upstox is None or not upstox.is_configured():
            return "skipped (Upstox not configured)"
        from app.providers import upstox_refresh as ur

        state = session.get(ProviderRefreshState, (ur.SOURCE_CODE, company.id))
        if state and state.next_due_at and state.next_due_at > datetime.now(UTC):
            return f"skipped (fresh until {state.next_due_at:%d/%m/%Y})"
        o = ur.refresh_company(session, upstox, company)
        return f"{o.status} {o.note}".strip()

    def documents():
        from app.acquisition.evidence_fetch import fetch_evidence

        if not company.website:
            return "skipped (no verified website)"
        rep = fetch_evidence(session, company, client)
        return f"{rep.status} (candidates {rep.candidates}, downloaded {rep.downloaded})"

    def enrich_step():
        from app.research import enrich

        if llm is None or not company.website:
            return "skipped (no website or no language model)"
        rep = enrich.enrich_company(session, company, client, llm)
        return f"stored {rep.stored}, discarded {rep.discarded}" + (
            f"; {rep.notes[0]}" if rep.notes else ""
        )

    def evidence():
        from app.evidence.engine import validate_company

        validate_company(session, company.id)
        return "validated"

    step("website", website)
    step("upstox", upstox_step)
    step("documents", documents)
    step("enrich", enrich_step)
    step("evidence", evidence)
    return out


def run_batch(
    session: Session, companies, *, steps=STEPS, client, llm=None, upstox=None, on_company=None
):
    run = UniverseRun()
    for company in companies:
        done = run_company(session, company, steps=steps, client=client, llm=llm, upstox=upstox)
        run.companies.append(done)
        if on_company:
            on_company(done)
    return run


def coverage(session: Session) -> dict:
    """What the universe looks like right now, from the stored state (no network)."""
    from app.acquisition import website_discovery as wd
    from app.providers import upstox_refresh as ur

    docs = dict(
        session.execute(
            select(EvidenceFetchRun.status, func.count()).group_by(EvidenceFetchRun.status)
        ).all()
    )
    return {
        "websites": wd.registry_summary(session),
        "upstox": ur.summary(session),
        "document_fetch_runs_by_status": docs,
        "companies_with_verified_external_quotes": session.scalar(
            select(func.count(func.distinct(CompanyEnrichment.company_id)))
        )
        or 0,
    }
